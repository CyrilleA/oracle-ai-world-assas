import assert from 'node:assert/strict';
import {initialGame,act,workflowCheck,view} from '../live/supply-game.mjs';
import {workflowCard} from '../site/supply-workflow.mjs';
const g=initialGame('VOLUMES1');g.phase='running';
for(const role of ['planning','buying','supplierA','supplierB'])g.players[role]={id:role,role};
const run=(role,op,b)=>act(g,g.players[role],op,b);
run('planning','request',{to:'buying',parentId:'NEED-1',quantity:40,delivery:960});const sourcing=g.documents.at(-1);
run('buying','request',{to:'supplierA',parentId:sourcing.id,quantity:40,delivery:900});const rfq=g.documents.at(-1);
const payload={requestId:rfq.id,quantity:30,unitPrice:1000,delivery:900};
run('supplierA','quote',payload);const original=g.documents.at(-1);
assert.throws(()=>run('supplierB','quote',{...payload,editId:original.id}),/demande reçue|appartient/);
assert.throws(()=>run('supplierA','quote',{...payload,quantity:70,editId:original.id}),/stock libre/);
assert.equal(original.status,'pending','Une modification impossible conserve la proposition originale');
assert.equal(workflowCheck(g,g.players.supplierA,{...payload,quantity:50,editId:original.id}).warnings.some(w=>w.includes('supérieur')),true);
run('supplierA','quote',{...payload,quantity:50,editId:original.id});const revised=g.documents.at(-1);
assert.equal(original.status,'superseded');assert.equal(revised.quantity,50);
assert.throws(()=>run('buying','accept',{id:original.id}),/déjà traitée/);
assert.throws(()=>run('supplierA','quote',{...payload,editId:original.id}),/déjà été traitée/);
assert.equal(view(g,g.players.supplierA).inventory.booked,0);
const card=workflowCard({...view(g,g.players.buying),documents:g.documents},revised);
assert.match(card,/50, pour 40 demandés/,'Le destinataire voit le dépassement avant de commander');
run('buying','accept',{id:revised.id});assert.equal(rfq.status,'closed');
assert.equal(view(g,g.players.supplierA).inventory.booked,50);
run('supplierA','quote',{...payload,quantity:45,replacesId:revised.id});const pendingRevision=g.documents.at(-1);
run('supplierA','quote',{...payload,quantity:55,editId:pendingRevision.id});const final=g.documents.at(-1);
assert.equal(revised.status,'accepted','L’engagement reste actif avant acceptation de la révision');
assert.equal(pendingRevision.status,'superseded');assert.equal(final.replacesId,revised.id);
run('buying','accept',{id:final.id});assert.equal(revised.status,'superseded');
assert.equal(view(g,g.players.supplierA).inventory.booked,55,'La révision ne réserve pas deux fois');
const purchase={requestId:sourcing.id,quantity:45,unitPrice:0,delivery:900};
run('buying','quote',purchase);const buying=g.documents.at(-1);
run('buying','quote',{...purchase,quantity:55,editId:buying.id});const changed=g.documents.at(-1);
assert.equal(buying.status,'superseded');run('planning','accept',{id:changed.id});
assert.equal(sourcing.status,'closed');
run('buying','quote',{...purchase,quantity:35,replacesId:changed.id});const reduction=g.documents.at(-1);
assert.equal(changed.status,'accepted');run('planning','accept',{id:reduction.id});
assert.equal(changed.status,'superseded');assert.equal(sourcing.status,'partial');
assert.equal(workflowCheck(g,g.players.buying,{...purchase,quantity:56,replacesId:reduction.id}).ok,false,'Achats : quantité plafonnée aux engagements fournisseurs');
assert.throws(()=>run('supplierA','quote',{...payload,quantity:121,replacesId:final.id}),/quantité autorisée/);
assert.match(workflowCard(view(g,g.players.buying),reduction),/data-wf-revise/);
console.log('Volumes : modification des offres Fournisseurs et Achats, surquantité signalée et acceptée, ancienne offre invalidée, autorisations, révisions sans double réservation et plafonds physiques vérifiés.');
